using System.Diagnostics;
using System.Net;
using System.Net.Sockets;
using Xunit;

namespace IISGate
{
    // Precompiled sites: aspnet_compiler (src/WebFormsForCore.AspNetCompiler) precompiles test/webForCore.Precompiled.Site
    // (CodeFile code-behind, a master page, a user control, App_Code, Global.asax, App_GlobalResources) into a target,
    // the host's build (test/webForCore.Precompiled.Host) goes into its bin_dotnet, as a deployment does, and the target
    // runs on Kestrel. Checked against aspnet_compiler's documented behaviour for fixed (non-updatable) and updatable (-u)
    // precompilation.
    public class PrecompilationTests
    {
        [Fact]
        public async Task NonUpdatableSiteRunsFromPrecompiledAssemblies()
        {
            using var site = new PrecompiledSite(updatable: false);
            Assert.Equal(0, site.CompilerExitCode);
            Assert.Contains("updatable=\"false\"", File.ReadAllText(Path.Combine(site.Target, "PrecompiledApp.config")));
            Assert.StartsWith("This is a marker file generated by the precompilation tool", File.ReadAllText(Path.Combine(site.Target, "Default.aspx")));
            Assert.False(File.Exists(Path.Combine(site.Target, "Default.aspx.cs")));
            Assert.False(Directory.Exists(Path.Combine(site.Target, "App_Code")));
            Assert.True(File.Exists(Path.Combine(site.Target, "bin_dotnet", "App_Code.dll")));
            Assert.NotEmpty(Directory.GetFiles(Path.Combine(site.Target, "bin_dotnet"), "default.aspx.*.compiled"));

            using var server = site.Run();
            var body = await server.Client.GetStringAsync("/Default.aspx");
            AssertRendered(body);

            // A page added after precompilation is refused, as IIS refuses it.
            File.WriteAllText(Path.Combine(site.Target, "New.aspx"), "<%@ Page Language=\"C#\" %>new=<%= 1 + 1 %>");
            var added = await server.Client.GetAsync("/New.aspx");
            Assert.Equal(HttpStatusCode.InternalServerError, added.StatusCode);
            Assert.Contains("The file &#39;/New.aspx&#39; has not been pre-compiled, and cannot be requested.", await added.Content.ReadAsStringAsync());
        }

        [Fact]
        public async Task UpdatableSiteKeepsMarkupEditable()
        {
            using var site = new PrecompiledSite(updatable: true);
            Assert.Equal(0, site.CompilerExitCode);
            Assert.Contains("updatable=\"true\"", File.ReadAllText(Path.Combine(site.Target, "PrecompiledApp.config")));
            var markup = File.ReadAllText(Path.Combine(site.Target, "Default.aspx"));
            Assert.DoesNotContain("CodeFile", markup, StringComparison.OrdinalIgnoreCase);
            Assert.Matches("inherits=\"DefaultPage, App_Web_[a-z0-9]+\"", markup);
            Assert.False(File.Exists(Path.Combine(site.Target, "Default.aspx.cs")));

            using var server = site.Run();
            AssertRendered(await server.Client.GetStringAsync("/Default.aspx"));

            // The markup is compiled at run time against the precompiled code-behind: edits take effect...
            File.WriteAllText(Path.Combine(site.Target, "Default.aspx"), markup.Replace("compiled=", "edited=yes;compiled="));
            Assert.Contains("edited=yes;", await GetEventually(server.Client, "/Default.aspx", "edited=yes;"));
            // ...and new pages compile.
            File.WriteAllText(Path.Combine(site.Target, "New.aspx"), "<%@ Page Language=\"C#\" %>new=<%= 1 + 1 %>");
            Assert.Equal("new=2", await server.Client.GetStringAsync("/New.aspx"));
        }

        [Fact]
        public void CompileErrorsFailThePrecompilation()
        {
            using var site = new PrecompiledSite(updatable: false, prepare: source =>
                File.WriteAllText(Path.Combine(source, "Broken.aspx"), "<%@ Page Language=\"C#\" %>\n<%= Missing %>"));
            Assert.NotEqual(0, site.CompilerExitCode);
            Assert.Matches(@"Broken\.aspx\(2\): error CS0103: The name 'Missing' does not exist in the current context", site.CompilerOutput);
        }

        [Fact]
        public void UsageListsAspnetCompilersSwitches()
        {
            var repository = AppContext.BaseDirectory;
            while (!File.Exists(Path.Combine(repository, "WebFormsForCore.slnx"))) repository = Path.GetDirectoryName(repository);
            var compiler = Path.Combine(repository, "src", "WebFormsForCore.AspNetCompiler", "bin", "Release", "net11.0", "aspnetcore_compiler.dll");
            var start = new ProcessStartInfo("dotnet") { RedirectStandardOutput = true, RedirectStandardError = true };
            start.ArgumentList.Add(compiler);
            start.ArgumentList.Add("-?");
            using var process = Process.Start(start);
            var output = process.StandardOutput.ReadToEnd() + process.StandardError.ReadToEnd();
            process.WaitForExit();
            Assert.Contains("ASP.NET Compilation Tool", output); // the banner (resources found)
            Assert.Contains("aspnet_compiler [-?] [-m metabasePath | -v virtualPath [-p physicalDir]]", output);
            Assert.Contains("-fixednames", output);
            Assert.Matches(@"(?m)^-b\s", output); // WebFormsForCore's bin folder switch
            Assert.Matches(@"(?m)^-t\s", output); // and target framework switch
        }

        private static void AssertRendered(string body)
        {
            Assert.Contains("<title>Precompiled site</title>", body); // App_GlobalResources
            Assert.Contains("[master]", body);
            Assert.Contains("greeting=<span id=\"Main_Greeting\">Hello, precompiled (App_Code)</span>;", body); // code-behind, App_Code
            Assert.Contains("started=Global.asax;", body);
            Assert.Contains("[badge:ok]", body); // user control
            Assert.Contains("compiled=True;", body);
        }

        private static async Task<string> GetEventually(HttpClient client, string path, string expected)
        {
            string body = null;
            for (var deadline = DateTime.UtcNow.AddSeconds(30); DateTime.UtcNow < deadline; await Task.Delay(250))
            {
                body = await client.GetStringAsync(path);
                if (body.Contains(expected)) break;
            }
            return body;
        }

        // A copy of the site precompiled into a temporary target, with the host's build in its bin_dotnet.
        private sealed class PrecompiledSite : IDisposable
        {
            private readonly string _root = Path.Combine(Path.GetTempPath(), "webforcore-precompiled-" + Guid.NewGuid().ToString("N"));

            public PrecompiledSite(bool updatable, Action<string> prepare = null)
            {
                var repository = AppContext.BaseDirectory;
                while (!File.Exists(Path.Combine(repository, "WebFormsForCore.slnx"))) repository = Path.GetDirectoryName(repository);

                var source = Path.Combine(_root, "site");
                Copy(Path.Combine(repository, "test", "webForCore.Precompiled.Site"), source, overwrite: true);
                prepare?.Invoke(source);
                Target = Path.Combine(_root, "target");

                var compiler = Path.Combine(repository, "src", "WebFormsForCore.AspNetCompiler", "bin", "Release", "net11.0", "aspnetcore_compiler.dll");
                // Relative paths: the compiler reads an argument starting with / as a switch.
                var start = new ProcessStartInfo("dotnet") { WorkingDirectory = _root, RedirectStandardOutput = true, RedirectStandardError = true };
                foreach (var argument in new[] { compiler, "-nologo", "-v", "/", "-p", "site", "-b", "bin_dotnet" }) start.ArgumentList.Add(argument);
                if (updatable) start.ArgumentList.Add("-u");
                start.ArgumentList.Add("target");
                using (var process = Process.Start(start))
                {
                    var error = process.StandardError.ReadToEndAsync();
                    CompilerOutput = process.StandardOutput.ReadToEnd() + error.Result;
                    process.WaitForExit();
                    CompilerExitCode = process.ExitCode;
                }

                // The app's build next to its precompiled pages; the compiler's App_*.dll and .compiled files stay.
                if (CompilerExitCode == 0)
                    Copy(Path.Combine(repository, "test", "webForCore.Precompiled.Host", "bin_dotnet"), Path.Combine(Target, "bin_dotnet"), overwrite: false);
            }

            public string Target { get; }

            public int CompilerExitCode { get; }

            public string CompilerOutput { get; }

            public Server Run() => new Server(Target);

            private static void Copy(string from, string to, bool overwrite)
            {
                Directory.CreateDirectory(to);
                foreach (var file in Directory.GetFiles(from))
                {
                    var destination = Path.Combine(to, Path.GetFileName(file));
                    if (overwrite || !File.Exists(destination)) File.Copy(file, destination, overwrite);
                }
                foreach (var directory in Directory.GetDirectories(from))
                {
                    var name = Path.GetFileName(directory);
                    if (name == "App_Data" || (name == "bin_dotnet" && overwrite)) continue; // the source's extracted machine.config, build output
                    Copy(directory, Path.Combine(to, name), overwrite);
                }
            }

            public void Dispose()
            {
                try { Directory.Delete(_root, recursive: true); }
                catch (IOException) { }
            }
        }

        private sealed class Server : IDisposable
        {
            private readonly Process _process;

            public Server(string directory)
            {
                var listener = new TcpListener(IPAddress.Loopback, 0);
                listener.Start();
                var address = new Uri($"http://127.0.0.1:{((IPEndPoint)listener.LocalEndpoint).Port}");
                listener.Stop();

                _process = Process.Start(new ProcessStartInfo("dotnet", $"bin_dotnet/webForCore.Precompiled.Host.dll --urls {address}")
                {
                    WorkingDirectory = directory,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                });
                _process.OutputDataReceived += (s, e) => { };
                _process.ErrorDataReceived += (s, e) => { };
                _process.BeginOutputReadLine();
                _process.BeginErrorReadLine();

                Client = new HttpClient { BaseAddress = address };
                var deadline = DateTime.UtcNow.AddSeconds(60);
                while (true)
                {
                    try
                    {
                        Client.GetAsync("/").GetAwaiter().GetResult();
                        break;
                    }
                    catch (HttpRequestException) when (DateTime.UtcNow < deadline && !_process.HasExited)
                    {
                        Thread.Sleep(250);
                    }
                }
            }

            public HttpClient Client { get; }

            public void Dispose()
            {
                Client.Dispose();
                if (!_process.HasExited)
                {
                    _process.Kill(entireProcessTree: true);
                    _process.WaitForExit(10000);
                }
                _process.Dispose();
            }
        }
    }
}
