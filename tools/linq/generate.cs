// Generates LINQ to SQL's SR, Strings and Error classes and string resources (#142), which referencesource doesn't
// publish, for src/webForCore.System.Data.Linq, and the list of cases test/webForCore.System.Data.Linq.Tests checks
// them with. The input is data:
// - external/referencesource/System.Data.Linq/System.Data.Linq.txt: the System.Data.Linq namespace's 70 strings, with
//   the exception type of each error (its "## ExceptionType=" annotations);
// - src/webForCore.System.Data.Linq/FrameworkData/System.Data.Linq.json: what .NET Framework 4.8's System.Data.Linq.dll
//   has (tools/linq/framework_data.cs): the strings of System.Data.Linq.Mapping and System.Data.Linq.SqlClient, and for
//   each Error method its name, parameters, exception type and constructor arguments.
// The two must agree where both say something (the System.Data.Linq strings, and the exception types the .txt names),
// and a member the data couldn't read must be referencesource's own (SqlClient/Error.cs); the generator fails otherwise.
//
// Usage: dotnet run tools/linq/generate.cs [-- --check]
// Writes src/webForCore.System.Data.Linq/Generated/ and test/webForCore.System.Data.Linq.Tests/Generated/; with --check,
// writes nothing and fails if those files aren't what it would write (CI runs it so).
#:property NuGetAudit=false
#:property PublishAot=false
using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using System.Xml.Linq;

bool check = args.Contains("--check");
string root = FindRoot();
string project = Path.Combine(root, "src/webForCore.System.Data.Linq");
string tests = Path.Combine(root, "test/webForCore.System.Data.Linq.Tests");
string referencesource = Path.Combine(root, "external/referencesource/System.Data.Linq");

var data = JsonNode.Parse(File.ReadAllText(Path.Combine(project, "FrameworkData/System.Data.Linq.json")))!.AsObject();
var errors = new List<string>();

// The resources: System.Data.Linq's from the .txt, the others from the data. The .txt's must be what .NET Framework has.
var (txtStrings, txtExceptionTypes) = ReadTxt(Path.Combine(referencesource, "System.Data.Linq.txt"));
var resources = new SortedDictionary<string, SortedDictionary<string, string>>(StringComparer.Ordinal);
foreach (var resource in data["resources"]!.AsArray())
{
    string baseName = ((string)resource!["name"]!)[..^".resources".Length];
    var strings = new SortedDictionary<string, string>(StringComparer.Ordinal);
    foreach (var (key, value) in resource["strings"]!.AsObject())
        strings[key] = (string)value!;
    resources[baseName] = strings;
}
if (!resources.TryGetValue("System.Data.Linq", out var frameworkLinqStrings))
    errors.Add("The data has no System.Data.Linq.resources");
else
{
    foreach (var name in frameworkLinqStrings.Keys.Union(txtStrings.Keys))
    {
        frameworkLinqStrings.TryGetValue(name, out var framework);
        txtStrings.TryGetValue(name, out var txt);
        if (framework != txt)
            errors.Add($"System.Data.Linq.txt's {name} isn't .NET Framework's: '{txt}' and '{framework}'");
    }
    resources["System.Data.Linq"] = txtStrings;
}

var output = new Dictionary<string, string>();
var cases = new StringBuilder();
foreach (var ns in resources.Keys)
{
    var classes = data["classes"]!.AsArray().Select(c => c!.AsObject()).ToDictionary(c => (string)c["type"]!);
    if (!classes.TryGetValue(ns + ".SR", out var sr) || !classes.TryGetValue(ns + ".Strings", out var stringsClass) || !classes.TryGetValue(ns + ".Error", out var errorClass))
    {
        errors.Add($"The data has no SR, Strings or Error class for {ns}");
        continue;
    }
    // SR: the base name must be the namespace, and the "..." and the two lengths are those of the truncation of long
    // arguments (GetString).
    var literals = sr["literals"]!.AsArray().Select(l => (string)l!).ToList();
    var integers = sr["integers"]!.AsArray().Select(i => (int)i!).ToList();
    if (!literals.SequenceEqual(["...", ns]) || !integers.SequenceEqual([1021, 1024]))
        errors.Add($"{ns}.SR isn't what the generator writes: literals {string.Join(", ", literals)}; integers {string.Join(", ", integers)}");
    foreach (var constant in sr["constants"]!.AsArray())
    {
        if ((string)constant!["name"]! != (string)constant["value"]! || !resources[ns].ContainsKey((string)constant["name"]!))
            errors.Add($"{ns}.SR.{constant["name"]} isn't a resource name");
    }

    var code = new StringBuilder();
    code.Append($$"""
        // <auto-generated>
        // Generated by tools/linq/generate.cs (#142) from {{(ns == "System.Data.Linq" ? "referencesource's System.Data.Linq.txt and " : "")}}FrameworkData/System.Data.Linq.json:
        // the members, exception types and messages of .NET Framework 4.8's System.Data.Linq.dll, in webForCore's code.
        // Don't edit; run the generator.
        // </auto-generated>
        using System;
        using System.Globalization;
        using System.Resources;

        namespace {{ns}}
        {
            internal static class SR
            {

        """);
    foreach (var name in sr["constants"]!.AsArray().Select(c => (string)c!["name"]!))
        code.Append($"        internal const string {name} = \"{name}\";\n");
    code.Append($$"""

                private static ResourceManager s_resources;

                internal static ResourceManager Resources => s_resources ??= new ResourceManager("{{ns}}", typeof(SR).Assembly);

                internal static string GetString(string name) => Resources.GetString(name, null);

                // As .NET Framework's: a string argument longer than 1,024 characters is cut to 1,021 and "...".
                internal static string GetString(string name, params object[] args)
                {
                    string format = Resources.GetString(name, null);
                    if (args == null || args.Length == 0)
                        return format;
                    for (int i = 0; i < args.Length; i++)
                    {
                        if (args[i] is string value && value.Length > 1024)
                            args[i] = value.Substring(0, 1021) + "...";
                    }
                    return string.Format(CultureInfo.CurrentCulture, format, args);
                }
            }

            internal static class Strings
            {

        """);
    var stringsMembers = new Dictionary<string, JsonObject>();
    foreach (var member in stringsClass["members"]!.AsArray().Select(m => m!.AsObject()))
    {
        string name = (string)member["name"]!;
        stringsMembers[name] = member;
        string body = Render(member["value"], ns, errors, $"{ns}.Strings.{name}");
        code.Append((string)member["kind"]! == "property"
            ? $"        internal static string {name} => {body};\n"
            : $"        internal static string {name}({Parameters(member)}) => {body};\n");
        cases.Append($"        new(\"{ns}.Strings\", \"{name}\", () => global::{ns}.Strings.{name}{((string)member["kind"]! == "property" ? "" : "(" + Arguments(member) + ")")}),\n");
    }
    code.Append("""
            }

            internal partial class Error
            {

        """);
    string handwritten = string.Concat(Directory.EnumerateFiles(referencesource, "*.cs", SearchOption.AllDirectories).Select(File.ReadAllText));
    foreach (var member in errorClass["members"]!.AsArray().Select(m => m!.AsObject()))
    {
        string name = (string)member["name"]!;
        if (member["value"] == null)
        {
            // Not generated code: referencesource has it (SqlClient/Error.cs).
            if (!Regex.IsMatch(handwritten, $@"\bstatic internal Exception {name}\(|\binternal static Exception {name}\("))
                errors.Add($"{ns}.Error.{name}: the data couldn't read it ({member["notRead"]}), and referencesource doesn't have it");
            continue;
        }
        var value = member["value"]!.AsObject();
        // The exception type System.Data.Linq.txt gives, where it gives one, must be .NET Framework's.
        if (ns == "System.Data.Linq" && value["arguments"]!.AsArray().FirstOrDefault()?["call"] is { } call
            && txtExceptionTypes.TryGetValue(((string)call!).Split('.')[^1].Replace("get_", ""), out var txtType)
            && !((string)value["new"]!).EndsWith("." + txtType, StringComparison.Ordinal))
            errors.Add($"{ns}.Error.{name}: System.Data.Linq.txt says {txtType}, .NET Framework throws {value["new"]}");
        code.Append($"        internal static Exception {name}({Parameters(member)}) => {Render(value, ns, errors, $"{ns}.Error.{name}")};\n");
        cases.Append($"        new(\"{ns}.Error\", \"{name}\", () => global::{ns}.Error.{name}({Arguments(member)})),\n");
    }
    code.Append("    }\n}\n");
    output[$"src/webForCore.System.Data.Linq/Generated/{ns}.cs"] = code.ToString();
    output[$"src/webForCore.System.Data.Linq/Generated/{ns}.resx"] = Resx(resources[ns]);
}

output["test/webForCore.System.Data.Linq.Tests/Generated/GeneratedCases.cs"] = $$"""
    // <auto-generated>
    // Generated by tools/linq/generate.cs (#142): a call of each member of the generated Strings and Error classes, with
    // each parameter's value "<name>". ErrorTests checks what each returns against FrameworkData/System.Data.Linq.json.
    // Don't edit; run the generator.
    // </auto-generated>
    using System;

    namespace System.Data.Linq.Tests
    {
        internal sealed record GeneratedCase(string Class, string Member, Func<object> Call);

        internal static class GeneratedCases
        {
            internal static readonly GeneratedCase[] All =
            [
    {{cases}}        ];
        }
    }

    """;

if (errors.Count > 0)
{
    foreach (var error in errors)
        Console.Error.WriteLine(error);
    return 1;
}

int different = 0;
foreach (var (path, text) in output)
{
    string full = Path.Combine(root, path);
    bool same = File.Exists(full) && File.ReadAllText(full) == text;
    if (same)
        continue;
    if (check)
    {
        different++;
        Console.Error.WriteLine($"{path} isn't what tools/linq/generate.cs writes: run it and commit the result");
    }
    else
    {
        Directory.CreateDirectory(Path.GetDirectoryName(full)!);
        File.WriteAllText(full, text, new UTF8Encoding(false));
        Console.WriteLine($"Wrote {path}");
    }
}
Console.WriteLine($"{output.Count} files, {resources.Values.Sum(r => r.Count)} strings in {resources.Count} resources{(check ? $", {different} different" : "")}");
return different > 0 ? 1 : 0;

// The C# for a value from the data: a constructor, a call, a parameter or a constant.
static string Render(JsonNode? node, string ns, List<string> errors, string where)
{
    var value = node!.AsObject();
    if (value["parameter"] is { } parameter)
        return Identifier((string)parameter!);
    if (value["literal"] is { } literal)
        return Literal((string)literal!);
    if (value["null"] != null)
        return "null";
    if (value["array"] is { } elementType)
        return $"new {TypeName((string)elementType!)}[] {{ {string.Join(", ", value["items"]!.AsArray().Select(i => Render(i, ns, errors, where)))} }}";
    var arguments = value["arguments"]!.AsArray().Select(a => Render(a, ns, errors, where)).ToList();
    if (value["new"] is { } type)
        return $"new {TypeName((string)type!)}({string.Join(", ", arguments)})";
    string method = (string)value["call"]!;
    if (method == ns + ".SR.GetString")
    {
        // SR.GetString(SR.Name, ...): the name is a constant of SR.
        var first = value["arguments"]![0]!.AsObject();
        if (first["literal"] == null)
        {
            errors.Add($"{where}: SR.GetString's first argument isn't a resource name");
            return "null";
        }
        arguments[0] = "SR." + (string)first["literal"]!;
        return $"SR.GetString({string.Join(", ", arguments)})";
    }
    int dot = method.LastIndexOf('.');
    string declaring = method[..dot], name = method[(dot + 1)..];
    if (declaring != ns + ".Strings")
        errors.Add($"{where}: a call to {method}, which the generator doesn't write");
    return name.StartsWith("get_", StringComparison.Ordinal) ? $"Strings.{name[4..]}" : $"Strings.{name}({string.Join(", ", arguments)})";
}

static string Parameters(JsonObject member) =>
    string.Join(", ", member["parameters"]!.AsArray().Select(p => $"{TypeName((string)p!["type"]!)} {Identifier((string)p["name"]!)}"));

// The test cases' arguments: "<name>" for each parameter.
static string Arguments(JsonObject member) =>
    string.Join(", ", member["parameters"]!.AsArray().Select(p => Literal($"<{(string)p!["name"]!}>")));

static string TypeName(string type) => type switch
{
    "System.Object" => "object",
    "System.String" => "string",
    _ => "global::" + type,
};

static string Identifier(string name) => name is "object" or "string" or "event" or "params" ? "@" + name : name;

static string Literal(string text)
{
    var result = new StringBuilder("\"");
    foreach (char c in text)
    {
        result.Append(c switch
        {
            '"' => "\\\"",
            '\\' => "\\\\",
            '\r' => "\\r",
            '\n' => "\\n",
            '\t' => "\\t",
            < ' ' => $"\\u{(int)c:x4}",
            _ => c.ToString(),
        });
    }
    return result.Append('"').ToString();
}

// A .resx with the strings, which the project embeds as <namespace>.resources, as .NET Framework's assembly has them.
static string Resx(SortedDictionary<string, string> strings)
{
    var root = new XElement("root",
        new XElement("resheader", new XAttribute("name", "resmimetype"), new XElement("value", "text/microsoft-resx")),
        new XElement("resheader", new XAttribute("name", "version"), new XElement("value", "2.0")),
        new XElement("resheader", new XAttribute("name", "reader"), new XElement("value", "System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089")),
        new XElement("resheader", new XAttribute("name", "writer"), new XElement("value", "System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089")));
    foreach (var (name, value) in strings)
        root.Add(new XElement("data", new XAttribute("name", name), new XAttribute(XNamespace.Xml + "space", "preserve"), new XElement("value", value)));
    var text = new StringBuilder();
    using (var writer = System.Xml.XmlWriter.Create(text, new System.Xml.XmlWriterSettings { Indent = true, NewLineChars = "\n", OmitXmlDeclaration = false, NewLineHandling = System.Xml.NewLineHandling.Entitize }))
        new XDocument(new XComment(" Generated by tools/linq/generate.cs (#142). Don't edit; run the generator. "), root).Save(writer);
    return text.ToString().Replace("encoding=\"utf-16\"", "encoding=\"utf-8\"") + "\n";
}

// System.Data.Linq.txt: Name=Value lines, with \r, \n, \t and \\ escapes; "## ExceptionType=" before a string names the
// exception type of its error; other lines starting with ; or # are comments.
static (SortedDictionary<string, string> Strings, Dictionary<string, string> ExceptionTypes) ReadTxt(string path)
{
    var strings = new SortedDictionary<string, string>(StringComparer.Ordinal);
    var types = new Dictionary<string, string>();
    string? pendingType = null;
    foreach (var raw in File.ReadAllLines(path))
    {
        string line = raw.Trim();
        if (line.StartsWith("## ExceptionType=", StringComparison.Ordinal))
        {
            pendingType = line["## ExceptionType=".Length..].Trim();
            continue;
        }
        if (line.Length == 0 || line[0] == ';' || line[0] == '#')
            continue;
        int equals = line.IndexOf('=');
        string name = line[..equals].Trim();
        strings[name] = Unescape(raw[(raw.IndexOf('=') + 1)..].TrimStart());
        if (pendingType != null)
            types[name] = pendingType;
        pendingType = null;
    }
    return (strings, types);
}

static string Unescape(string text)
{
    var result = new StringBuilder();
    for (int i = 0; i < text.Length; i++)
    {
        if (text[i] != '\\' || i + 1 == text.Length)
        {
            result.Append(text[i]);
            continue;
        }
        char next = text[++i];
        result.Append(next switch { 'r' => '\r', 'n' => '\n', 't' => '\t', _ => next });
    }
    return result.ToString();
}

static string FindRoot()
{
    for (var directory = new DirectoryInfo(Directory.GetCurrentDirectory()); directory != null; directory = directory.Parent)
    {
        if (File.Exists(Path.Combine(directory.FullName, "WebFormsForCore.slnx")))
            return directory.FullName;
    }
    throw new InvalidOperationException("Run the generator in the webForCore repository");
}
