#!/usr/bin/env python3
"""Generates a resource accessor class (SR, Res, ...) from a .resx file: one constant per resource name, and GetString.

Microsoft's build generates these classes for each assembly; WebFormsForCore had decompiled copies of them. webForCore
generates its own from the project's .resx (docs/LICENSING.md).

Usage: gen_sr.py <file.resx> <output.cs> --namespace N --class SR --resource <manifest resource name>
                 [--attributes] [--public]
--attributes also emits <class>DescriptionAttribute and <class>CategoryAttribute, which look their text up by name.
"""
import argparse
import re
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser()
parser.add_argument("resx")
parser.add_argument("output")
parser.add_argument("--namespace", required=True)
parser.add_argument("--class", dest="cls", default="SR")
parser.add_argument("--resource", required=True)
parser.add_argument("--attributes", action="store_true")
args = parser.parse_args()

names = [d.get("name") for d in ET.parse(args.resx).getroot().iter("data") if d.get("type") is None and d.get("mimetype") is None]
cls = args.cls
lines = [
    f"// <auto-generated> by tools/lift/gen_sr.py from {args.resx.split('/src/', 1)[-1]}; do not edit. MIT license (webForCore).",
    "using System.Globalization;",
    "using System.Resources;",
    "",
    f"namespace {args.namespace}",
    "{",
    f"\tinternal static partial class {cls}",
    "\t{",
    f"\t\tprivate static ResourceManager s_resources;",
    "",
    f"\t\tinternal static ResourceManager Resources => s_resources ??= new ResourceManager(\"{args.resource}\", typeof({cls}).Assembly);",
    "",
    "\t\t// Strings longer than this are shortened when inserted into a message.",
    "\t\tprivate const int MaxArgumentLength = 1024;",
    "",
    "\t\tinternal static string GetString(string name) => Resources.GetString(name, null);",
    "",
    "\t\tinternal static string GetString(string name, out bool usedFallback)",
    "\t\t{",
    "\t\t\tusedFallback = false;",
    "\t\t\treturn GetString(name);",
    "\t\t}",
    "",
    "\t\tinternal static string GetString(string name, params object[] args)",
    "\t\t{",
    "\t\t\tstring format = GetString(name);",
    "\t\t\tif (format == null || args == null || args.Length == 0)",
    "\t\t\t\treturn format;",
    "\t\t\tfor (int i = 0; i < args.Length; i++)",
    "\t\t\t{",
    "\t\t\t\tif (args[i] is string s && s.Length > MaxArgumentLength)",
    "\t\t\t\t\targs[i] = s.Substring(0, MaxArgumentLength - 3) + \"...\";",
    "\t\t\t}",
    "\t\t\treturn string.Format(CultureInfo.CurrentCulture, format, args);",
    "\t\t}",
    "",
    "\t\tinternal static object GetObject(string name) => Resources.GetObject(name, null);",
    "",
]
for name in names:
    ident = re.sub(r"\W", "_", name)
    if ident[0].isdigit():
        ident = "_" + ident
    lines.append(f"\t\tinternal const string {ident} = \"{name}\";")
lines += ["\t}"]
if args.attributes:
    for kind, base in (("Description", "System.ComponentModel.DescriptionAttribute"), ("Category", "System.ComponentModel.CategoryAttribute")):
        lines += [
            "",
            "\t[System.AttributeUsage(System.AttributeTargets.All)]",
            f"\tinternal sealed class {cls}{kind}Attribute : {base}",
            "\t{",
            f"\t\tpublic {cls}{kind}Attribute(string name) : base(name) {{ }}",
            "",
        ]
        if kind == "Description":
            lines += [
                "\t\tprivate bool _looked;",
                "",
                "\t\tpublic override string Description",
                "\t\t{",
                "\t\t\tget",
                "\t\t\t{",
                "\t\t\t\tif (!_looked)",
                "\t\t\t\t{",
                "\t\t\t\t\t_looked = true;",
                f"\t\t\t\t\tDescriptionValue = {cls}.GetString(base.Description) ?? base.Description;",
                "\t\t\t\t}",
                "\t\t\t\treturn base.Description;",
                "\t\t\t}",
                "\t\t}",
            ]
        else:
            lines += [f"\t\tprotected override string GetLocalizedString(string value) => {cls}.GetString(value) ?? value;"]
        lines += ["\t}"]
lines += ["}", ""]
with open(args.output, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"{len(names)} names -> {args.output}")
